"""tools/deferred_register.py — docs/DEFERRED_SUTRAS.md: every Laghukaumudī sūtra from 1.1.1 on that is not yet exercised by the engine, with the stage
(docs/ALL_SUTRA_PLAN.md L1–L6) and prakaraṇa at which it is finished. Run after each session:  python3 -m tools.deferred_register
Inputs: docs/data/lk_worklist.json (python3 -m tools.lk_plan), sig/sutra_class.json (status), data/inputs/prakarana_map.json, docs/data/deferred_reasons.json (hand-written)."""
import collections
import json
import pathlib
import time

R = pathlib.Path(__file__).resolve().parent.parent
DONE = {"confident", "confident_structural", "working"}
STAGE = {"1": "L1", "2": "L1", "3": "L4", "4": "L5", "5": "L5", "6": "L2", "7": "L3", "8": "L3"}
key = lambda i: tuple(int(x) for x in i.split("."))


def main() -> int:
    rows = json.loads((R / "docs/data/lk_worklist.json").read_text())
    st = {r["id"]: r["status"] for r in json.loads((R / "sig/sutra_class.json").read_text())["rows"]}
    pm = json.loads((R / "data/inputs/prakarana_map.json").read_text()).get("sutra_to_prakarana", {})
    why = json.loads((R / "docs/data/deferred_reasons.json").read_text())
    openl = [r["id"] for r in rows if st.get(r["id"], r["status"]) not in DONE]
    out = ["# Deferred sūtras — Laghukaumudī scope, 1.1.1 onward", "",
           "Generated by `python3 -m tools.deferred_register` (run it at the end of every session, after `python3 -m tools.sutra_class` and `python3 -m tools.lk_plan`; "
           f"last run {time.strftime('%Y-%m-%d')}). Stages are those of `docs/ALL_SUTRA_PLAN.md`; the shortcut ledger is `docs/SHORTCUT_LEDGER.md`.", "",
           "## Counts (Laghukaumudī sūtras not yet exercised: placeholder, pending, gate-only, unexercised)", "",
           "| Adhyāya | LK sūtras | open | stage |", "|---|---|---|---|"]
    for a in "12345678":
        tot = [r for r in rows if r["id"].startswith(a + ".")]
        op = [i for i in openl if i.startswith(a + ".")]
        out.append(f"| {a} | {len(tot)} | {len(op)} | {STAGE[a]} |")
    out += ["", "## Left out on purpose (reason · missing feature · finished at · prakaraṇa)", "",
            "| Sūtra | What | Missing feature | Finished at | Prakaraṇa |", "|---|---|---|---|---|"]
    for sid, (w, feat, stage, prak) in sorted(why["sutras"].items(), key=lambda kv: key(kv[0])):
        out.append(f"| {sid} | {w} | {feat} | {stage} | {prak} |")
    out += ["", "## Wider than a sūtra", "", "| Item | Finished at | Prakaraṇa |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in why["wider"]]
    out += ["", "## All open sūtras by pāda (stage · prakaraṇa)", ""]
    by = collections.defaultdict(list)
    for i in openl:
        by[".".join(i.split(".")[:2])].append(i)
    for pada in sorted(by, key=lambda p: key(p + ".0")):
        ids = by[pada]
        prak = collections.Counter((pm.get(i) or ["?"])[0] if isinstance(pm.get(i), list) else pm.get(i, "?") for i in ids).most_common(3)
        out.append(f"**{pada}** ({STAGE[pada[0]]}; {', '.join(p for p, _ in prak)}): " + ", ".join(i.split(".")[2] for i in ids))
        out.append("")
    (R / "docs/DEFERRED_SUTRAS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(openl)} open of {len(rows)} → docs/DEFERRED_SUTRAS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
