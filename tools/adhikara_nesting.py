"""tools/adhikara_nesting.py — the adhikāra heads of the whole Aṣṭādhyāyī as ranges, their nesting / overlap, and what the Kāśikā says about each.

    python3 -m tools.adhikara_nesting     # → data/inputs/adhikara_nesting.json + docs/ADHIKARA_NESTING.md
Ranges: brain edges rel='adhikara' (+ tools.build_scope_index.EXTEND, the Kāśikā-sourced extensions). Validation: Kāśikā on the head sūtra
(`texts`, source='kashika'): grade K = it says so itself (अधिकारोऽयम् / ऊर्ध्वमनुक्रमिष्यामः / अधिकृतम्), E = edge only (no marker; the range is
the database's, unconfirmed), and a hole in the range is reported (a nivṛtti inside the scope). Relation of two heads: nested (one range inside
the other) · overlap (they share sūtras but neither contains the other, e.g. 4.1.3 strī ends at 4.1.81, inside taddhita 4.1.76–5.4.160) · disjoint."""
from __future__ import annotations

import json
import re
import sqlite3
from collections import defaultdict

from tools.build_scope_index import DB, EXTEND, ROOT, _key

OUT = ROOT / "data" / "inputs" / "adhikara_nesting.json"
DOC = ROOT / "docs" / "ADHIKARA_NESTING.md"
MARK = re.compile(r"अधिकारोऽयम्|ऊर्ध्वमनुक्रमिष्यामः|इत्यधिकृतं|अधिकृतं|अधिकारः")


def main() -> dict:
    c = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    ids = sorted((r[0] for r in c.execute("select id from sutras")), key=_key)
    pos = {s: i for i, s in enumerate(ids)}
    members: dict[str, set[str]] = defaultdict(set)
    for a, b in c.execute("select src, dst from edges where rel='adhikara'"):
        members[a.removeprefix("s:")].add(b.removeprefix("s:"))
    for h, ms in EXTEND.items():
        members[h] |= set(ms)
    kas = dict(c.execute("select sutra_id, content from texts where source='kashika'"))
    heads: dict[str, dict] = {}
    for h, ms in members.items():
        p = sorted({pos[x] for x in ms | {h} if x in pos})
        heads[h] = {"start": ids[p[0]], "end": ids[p[-1]], "n": len(p), "holes": (p[-1] - p[0] + 1) - len(p),
                    "grade": "K" if MARK.search(kas.get(h, "")) else "E"}
    rel: dict[str, dict[str, list[str]]] = {h: {"inside": [], "contains": [], "overlaps": []} for h in heads}
    for a in heads:
        for b in heads:
            if a == b:
                continue
            ia, ib = (pos[heads[a]["start"]], pos[heads[a]["end"]]), (pos[heads[b]["start"]], pos[heads[b]["end"]])
            if ib[0] >= ia[0] and ib[1] <= ia[1]:
                rel[a]["contains"].append(b); rel[b]["inside"].append(a)
            elif ia[0] <= ib[1] and ib[0] <= ia[1] and not (ia[0] >= ib[0] and ia[1] <= ib[1]):
                rel[a]["overlaps"].append(b)
    for h in heads:
        heads[h].update({k: sorted(set(v), key=_key) for k, v in rel[h].items()})
    out = dict(sorted(heads.items(), key=lambda kv: _key(kv[0])))
    OUT.write_text(json.dumps({"note": "generated by tools/adhikara_nesting.py; do not edit", "heads": out}, ensure_ascii=False, indent=1))
    L = ["# Adhikāra nesting — whole Aṣṭādhyāyī (generated by tools/adhikara_nesting.py)", "",
         f"{len(out)} heads · grade K = the Kāśikā on the head says it is an adhikāra ({sum(v['grade']=='K' for v in out.values())}) · grade E = database edge only, no Kāśikā marker ({sum(v['grade']=='E' for v in out.values())}) · ranges with a hole (nivṛtti inside): {sum(v['holes']>0 for v in out.values())}", "",
         "| head | range | n | Kāśikā | holes | inside (enclosing heads) | overlaps |", "|---|---|---|---|---|---|---|"]
    for h, v in out.items():
        L.append(f"| {h} | {v['start']}–{v['end']} | {v['n']} | {v['grade']} | {v['holes']} | {', '.join(v['inside'])} | {', '.join(v['overlaps'])} |")
    DOC.write_text("\n".join(L) + "\n")
    return out


if __name__ == "__main__":
    o = main()
    print(len(o), "heads")
