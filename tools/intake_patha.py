"""tools/intake_patha.py — intake of Pāṇini's own pāṭhas from the reference brain (data-master), reproducible, nothing typed by hand.

    python3 -m tools.intake_patha            # writes data/inputs/{unadi_patha,dhatupatha_ganasutras,ganapatha_overlay}.json + sig/patha_intake.json
    PATHA_SRC=/path/to/data-master python3 -m tools.intake_patha

Sources (all ashtadhyayi.com data via the brain): ``unaadi/data.txt`` (uṇādi-pāṭha, Siddhānta-kaumudī edition), ``dhatu/data.txt`` (dhātupāṭha with
its gaṇasūtras and per-root ``antarganas``), ``ashtadhyayi-ai/db/ashtadhyayi.db`` table ganapath, ``sutraani/kashika.txt`` (Kāśikā, the cross-check).
Each step ends in assertions: a count or a Kāśikā cross-check that fails stops the run. The decisions (derived by the engine / stored from a pāṭha /
source needed) are in ``docs/data/patha_xref_classified.json`` and ``docs/REFERENCE_PATHAS_AUTHORITY.md``.

``ganapatha_overlay.json`` is applied by ``tools/build_ganapatha_full.py``: sūtra-id fixes, ākṛtigaṇa flags (from the Kāśikā), in-place expansion of
the gaṇasūtras that only enumerate members (sarvādi), sense-restricted members found inside the brain's <<…>> notes, and the sub-gaṇas that the Kāśikā
names as a stretch of another gaṇa (haritādi of bidādi, kaṇvādi of gargādi, pūrvādi / ḍatarādi of sarvādi)."""
from __future__ import annotations

import difflib
import json
import os
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
SRC = Path(os.environ.get("PATHA_SRC", Path.home() / "data-master"))
IN = ROOT / "data" / "inputs"
REPORT = ROOT / "sig" / "patha_intake.json"

_S = None


def sl(text: str) -> str:
    """Flat SLP1 of Devanāgarī, word by word (the converter ignores whitespace)."""
    global _S
    if _S is None:
        from phonology.tokenizer import devanagari_to_slp1_flat as _S
    return " ".join(_S(w) for w in text.split())


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def _kashika() -> dict:
    return _load(SRC / "sutraani" / "kashika.txt")


def kkey(sid: str) -> str:
    a, p, n = sid.split(".")
    return f"{a}{p}{int(n):03d}"


# ---- 1. uṇādi-pāṭha ------------------------------------------------------------------------------------------------------------------

UNADI_EXPECTED = 748


def unadi(report: dict) -> None:
    rows = _load(SRC / "unaadi" / "data.txt")["data"]
    entries, per_pada, bad = [], {}, []
    for r in rows:
        i = str(r["i"])
        pada, no = int(i[0]), int(i[1:])
        per_pada.setdefault(pada, []).append(no)
        sutra, pr = r["sutra"].strip(), r["pratyay"].strip()
        if pr not in sutra:
            bad.append(i)                       # the pratyaya field is the name (uṇ, kvip …), the sūtra spells it with sandhi: informational only
        entries.append({"id": int(i), "pada": pada, "no": no, "sutra_dev": sutra, "sutra_slp1": sl(sutra), "pratyaya_dev": pr, "pratyaya_slp1": sl(pr),
                        "examples_sk": r.get("sk", "")})
    assert len(entries) == UNADI_EXPECTED, len(entries)
    for pada, nos in per_pada.items():
        assert nos == list(range(1, len(nos) + 1)), f"uṇādi pāda {pada}: numbering has a gap"      # contiguous 1..n in every pāda
    assert len({e["id"] for e in entries}) == len(entries)
    out = {"_doc": "Uṇādi-sūtra pāṭha (5 pādas, 748 sūtras) — Pāṇinian pāṭha, 3.3.1 uṇādayo bahulam; 3.4.75 uṇādayaḥ. Generated by tools/intake_patha.py; each entry is an authority record {pATha:'uRAdi', entry:id}.",
           "source": {"file": "data-master/unaadi/data.txt", "origin": "ashtadhyayi.com unaadi (Siddhānta-kaumudī uṇādi-pāṭha)", "edition": "SK, 5 pādas"},
           "count": len(entries), "per_pada": {str(p): len(n) for p, n in sorted(per_pada.items())}, "entries": entries}
    (IN / "unadi_patha.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    # cross-check against the Siddhānta-kaumudī text of the brain: how many uṇādi sūtras occur there verbatim
    sk = " ".join(v for v in _load(SRC / "sutraani" / "kaumudi.txt").values() if isinstance(v, str))
    norm = lambda s: re.sub(r"\s+", "", s)
    sk_n = norm(sk)
    hit = sum(1 for e in entries if norm(e["sutra_dev"]) in sk_n)
    report["unadi"] = {"count": len(entries), "per_pada": out["per_pada"], "pratyaya_not_a_word_of_sutra": len(bad), "in_sk_text_verbatim": hit}


# ---- 2. dhātupāṭha: gaṇasūtras and the per-root antargaṇas ---------------------------------------------------------------------------

def dhatu(report: dict) -> None:
    src = _load(SRC / "dhatu" / "data.txt")["data"]
    eng = _load(IN / "dhatupatha_upadesha.json")["entries"]
    mine = {e["dhatupatha_id"]: e for e in eng if e.get("dhatupatha_id")}
    gs = []
    for r in src:
        if "ganasutra" in (r.get("tags") or ""):
            gs.append({"dhatupatha_id": r["baseindex"], "gana": int(r["gana"]), "text_dev": r["dhatu"], "text_slp1": sl(r["dhatu"]), "note_dev": r.get("ganasutra_note", "")})
    assert len(gs) == 30 and not any(g["dhatupatha_id"] in mine for g in gs)         # the engine's entries are all roots; these rows are the gaṇasūtras
    out = {"_doc": "Dhātupāṭha gaṇasūtras (ghaṭādayo mitaḥ, svādayaḥ oditaḥ …): rows of the pāṭha that are not roots. Generated by tools/intake_patha.py.",
           "source": {"file": "data-master/dhatu/data.txt", "origin": "ashtadhyayi.com dhatu", "edition": "tags: ganasutra"}, "count": len(gs), "entries": gs}
    (IN / "dhatupatha_ganasutras.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    # the antargaṇas the engine's dhātu entries carry against the pāṭha's own marks
    diff = []
    for r in src:
        if "ganasutra" in (r.get("tags") or ""):
            continue
        e = mine.get(r["baseindex"])
        want = [x for x in (r.get("antarganas") or "").split(",") if x]
        if e is None:
            diff.append({"id": r["baseindex"], "problem": "root not in engine", "source": want})
        elif sorted(e.get("antarganas") or []) != sorted(want):
            diff.append({"id": r["baseindex"], "root": r["aupadeshik"], "engine": e.get("antarganas"), "source": want})
    # Kāśikā bounds of the named stretches (1.2.1, 3.1.55, 6.1.6, 7.2.45): first and last root of each antargaṇa as the pāṭha marks them
    order = [r["baseindex"] for r in src if "ganasutra" not in (r.get("tags") or "")]
    bounds = {}
    for name in ("कुटादिः", "द्युतादिः", "पुषादिः", "जक्षित्यादिः", "रधादिः"):
        ids = [r["baseindex"] for r in src if name in (r.get("antarganas") or "").split(",")]
        first, last = next(r for r in src if r["baseindex"] == ids[0]), next(r for r in src if r["baseindex"] == ids[-1])
        bounds[name] = {"n": len(ids), "first": f"{first['aupadeshik']} {first['baseindex']}", "last": f"{last['aupadeshik']} {last['baseindex']}"}
    kut = [r["baseindex"] for r in src if "कुटादिः" in (r.get("antarganas") or "").split(",")]
    stray = [i for i in kut if i > "06.0137"]            # Kāśikā 1.2.1: kuṭ kauṭilye … kuṅ śabde (06.0093 – 06.0137 with kūṅ): a mark beyond is the source's stray, the engine does not take it
    assert stray == ["06.0174"] and [d["id"] for d in diff] == stray, (stray, diff)
    assert bounds["जक्षित्यादिः"]["n"] == 7 and bounds["रधादिः"]["n"] == 8      # Kāśikā 6.1.6 (jakṣ + ṣaṭ), 7.2.45 (raddh … aṣṭābhyaḥ)
    assert bounds["द्युतादिः"]["first"].startswith("द्युतँ") and bounds["द्युतादिः"]["last"].startswith("कृपूँ")      # Kāśikā 1.3.91: dyut … kṛpū
    report["dhatu"] = {"ganasutras": len(gs), "antargana_marks": sum(1 for r in src if r.get("antarganas")), "engine_marks": sum(1 for e in eng if e.get("antarganas")),
                       "differences_engine_vs_source": diff, "source_stray_marks_not_taken": stray, "bounds": bounds}


# ---- 3. Gaṇapāṭha overlay ------------------------------------------------------------------------------------------------------------

SUTRA_FIX = {"SramaRAdiH": ("3.1.70", "2.1.70", "श्रमण")}        # name, (brain's id, right id, a word of the Kāśikā at the right id): the sūtra is 2.1.70 kumāraḥ śramaṇādibhiḥ
# a gaṇasūtra of the brain's notes that only enumerates members: key → (note, Kāśikā id of the sūtra whose first sentence spells them)
EXPAND = {"sarvAdiH": [("pUrvaparAvara", "1.1.34", r"^(.*?) इत्येतेषां"), ("svam", "1.1.35", None), ("antara", "1.1.36", None)]}      # note prefix (SLP1)
# stretches of another gaṇa that the Kāśikā names: new gaṇa key → (sūtra, parent gaṇa, first member or None, size or None, evidence)
SUB_GANAS = {"haritAdiH": ("4.1.100", "bidAdiH", "harita", None, "Kāśikā 4.1.100 haritādir bidādyantargaṇaḥ (the stretch from harita to the end of bidādi)"),
             "kaRvAdiH": ("4.2.111", "gargAdiH", "kaRva", None, "Kaumudī 4.2.111 'kaṇvo gargādiḥ': kaṇva is a member of gargādi, kaṇvādi is the stretch from kaṇva to its end (kurvādi's gaṇasūtra: kaṇvādivat)"),
             "pUrvAdiH": ("7.1.16", "sarvAdiH", "pUrva", 9, "Kāśikā 7.1.16 pūrvādibhyo navabhyaḥ: the nine from pūrva in sarvādi's order"),
             "qatarAdiH": ("7.1.25", "sarvAdiH", "qatara", 5, "Kāśikā 7.1.25 ḍatarādibhyaḥ pañcabhyaḥ: ḍatara ḍatama anya anyatara itara (sarvādi's five)")}
# gaṇas that name their members as a stretch of another gaṇa and an engine-derived suffix: nothing stored, the engine derives (4.3.54 yat)
DERIVED = {"vargyAdiH": {"from_gaNa": "digAdiH", "from_member": "varga", "to": "end", "pratyaya": "yat", "sutra": "4.3.54", "evidence": "Kāśikā 6.2.131 vargyādayaḥ … dig-ādiṣu varga pūga gaṇa pakṣa ity evamādayo ye paṭhitāḥ, ta eva yat-pratyayāntāḥ"}}
AKRTI_RE = re.compile("ाकृतिगण|आकृतिगण")
OPEN_NOT_IN_PATHA = {"indrajananAdiH": ("4.3.88", "Kāśikā 4.3.88 indrajananādir ākṛtigaṇaḥ prayogato 'nusartavyaḥ, prātipadikeṣu na paṭhyate: usage-attested, not in the pāṭha; admitted only through a reviewed extension row")}


def _tokens(s: str) -> list[str]:
    return [t for t in re.split(r"\s+", s.strip()) if t]


def _stem(tok: str) -> str:
    """Stem of a gaṇa-note word: the brain writes the nominative with sandhi (pāraskaro, kiṣkuḥ)."""
    s = sl(tok)
    if s.endswith("H"):
        s = s[:-1]
    if tok.endswith("ो"):
        s = s[:-1] + "a"
    return s


def gana_overlay(report: dict) -> dict:
    from phonology.tokenizer import devanagari_to_slp1_flat as flat

    kas = _kashika()
    con = sqlite3.connect(SRC / "ashtadhyayi-ai" / "db" / "ashtadhyayi.db")
    rows = con.execute("select id, name_slp1, sutra, words from ganapath order by id").fetchall()
    per_sutra = {}
    for _id, name, sutra, _w in rows:
        per_sutra.setdefault(sutra, []).append(name)
    kas_words = lambda sid: set(re.findall(r"[ऀ-ॿ]+", kas.get(kkey(sid), "")))
    ov: dict = {"_doc": __doc__.strip().splitlines()[0], "source": "tools/intake_patha.py (brain db ganapath + Kāśikā cross-check)", "sutra_fix": {}, "akrti": {}, "expansions": {}, "extra": {}, "sub_ganas": {}}
    log: dict = {"corrections": [], "unverified_notes": 0, "akrti_unresolved": []}

    for name, (was, now, word) in SUTRA_FIX.items():
        assert word in kas[kkey(now)], f"Kāśikā {now} does not mention {word}"
        ov["sutra_fix"][name] = {"was": was, "sutra": now, "evidence": f"Kāśikā {now} lists {word}…"}

    key_of = {}
    for _id, name, sutra, words in rows:
        key = name
        if name in key_of:
            key = f"{name}#{sutra}"
        key_of[key] = (name, sutra, words)
        # ākṛtigaṇa: the Kāśikā of the sūtra says so (a sūtra with several gaṇas is left unresolved unless the name is in the sentence)
        m = AKRTI_RE.search(kas.get(kkey(sutra), ""))
        if m:
            if len(per_sutra[sutra]) == 1:
                ov["akrti"][key] = f"Kāśikā {sutra}: ākṛtigaṇa"
            else:
                log["akrti_unresolved"].append(f"{sutra} {per_sutra[sutra]}")
        # notes
        notes = re.findall(r"<<(.*?)>>", words)
        plain = [t for t in re.split(r"[।॥\n]+", re.sub(r"<<.*?>>", " ", words)) if t.strip()]
        if not notes:
            continue
        kw = kas_words(sutra) | ({w for sid in ("1.1.34", "1.1.35", "1.1.36") for w in kas_words(sid)} if sutra == "1.1.27" else set())
        extra = {"gaNasUtra": [], "members_restricted": []}
        for note in notes:
            note = note.strip()
            toks = _tokens(note)
            cand = None
            if 2 <= len(toks) <= 4 and not re.search(r"(भ्यः|स्य|ाम्|ेषु)$", toks[0]) and not toks[0].endswith(("े", "ि")) and "च" not in toks and "वा" not in toks:
                st = _stem(toks[0])
                dev_stem = toks[0].rstrip("ः").rstrip("ो") if toks[0].endswith(("ः", "ो")) else toks[0]
                ok = any(w.startswith(dev_stem) for w in kw)
                fix = None
                if not ok and len(plain) == 0:          # a gaṇa that is nothing but notes (pāraskarādi): spelling slips of the brain are repaired from the Kāśikā word
                    near = difflib.get_close_matches(dev_stem, sorted(kw), n=1, cutoff=0.7)
                    if near and abs(len(near[0]) - len(dev_stem)) <= 1:
                        fix = near[0]
                        st = _stem(fix)
                        ok = True
                        log["corrections"].append({"gana": key, "brain": toks[0], "kashika": fix})
                cand = {"member": st, "surface_dev": toks[0], "gloss_dev": " ".join(toks[1:]), "verified_in_kashika": ok}
                if fix:
                    cand["repaired_from"] = toks[0]
            if cand and any(c["member"] == cand["member"] and c["gloss_dev"] == cand["gloss_dev"] for c in extra["members_restricted"]):
                continue
            if cand:
                extra["members_restricted"].append(cand)
                if not cand["verified_in_kashika"]:
                    log["unverified_notes"] += 1
            else:
                extra["gaNasUtra"].append({"dev": note, "slp1": sl(note)})
        ov["extra"][key] = extra

    # sarvādi's three enumerating gaṇasūtras: expand in place from the Kāśikā sentence of 1.1.34, and sva / antara from 1.1.35–36
    for key, specs in EXPAND.items():
        _w = key_of[key][2]
        for prefix, sid, rx in specs:
            note_slp1 = next("".join(flat(w) for w in n.split()) for n in re.findall(r"<<(.*?)>>", _w) if "".join(flat(w) for w in n.split()).startswith(prefix))
            text = kas[kkey(sid)]
            if rx:
                members = _tokens(re.match(rx, text).group(1))
            else:
                members = [_first_member(text)]
            ms = [flat(m) for m in members]
            assert all(any(w.startswith(m) for w in kas_words(sid)) for m in members)
            ov["expansions"].setdefault(key, {})[note_slp1] = ms
    # pāraskarādi is nothing but notes: a member is a verified nominative with a one-word gloss (देशः, नदी …); the others are its gaṇasūtras 163 / 164 (Kāśikā)
    ps = ov["extra"]["pAraskarAdiH"]
    seen, keep, rules = set(), [], []
    for c in ps["members_restricted"]:
        if c["verified_in_kashika"] and len(c["gloss_dev"].split()) <= 1 and c["member"] not in seen:
            seen.add(c["member"])
            keep.append(c)
        elif not c["verified_in_kashika"] and len(c["gloss_dev"].split()) <= 1:
            log["unverified_notes"] += 0
            keep.append(c)
        elif len(c["gloss_dev"].split()) > 1:
            rules.append({"dev": c["surface_dev"] + " " + c["gloss_dev"], "slp1": sl(c["surface_dev"] + " " + c["gloss_dev"])})
    ps["members_restricted"] = keep
    ps["gaNasUtra"] += rules
    ps["members"] = [c["member"] for c in keep if c["verified_in_kashika"]]
    ps["akrti_evidence"] = "Kāśikā 6.1.157 pāraskaraprabhṛtir ākṛtigaṇaḥ"
    ov["akrti"]["pAraskarAdiH"] = ov["akrti"].get("pAraskarAdiH") or "Kāśikā 6.1.157: ākṛtigaṇa"
    assert ps["members"] == ["pAraskara", "kAraskara", "raTaspA", "kizku", "kizkinDA"] and len(rules) == 2, (ps["members"], rules)      # Kāśikā 6.1.157
    ov["extra"]["vargyAdiH"] = {"derived": DERIVED["vargyAdiH"]}
    ov["open_not_in_patha"] = {k: {"sutra": s, "evidence": e} for k, (s, e) in OPEN_NOT_IN_PATHA.items()}
    ov["sutra_aliases"] = {}      # a sūtra that reads another sūtra's gaṇa (docs/data/patha_xref_classified.json, class alias), checked in the Kāśikā of the reading sūtra
    for ek, row in _load(ROOT / "docs" / "data" / "patha_xref_classified.json")["entries"].items():
        if row["class"] == "alias":
            sid = ek.split("|")[0]
            assert row["kashika_word"] in kas[kkey(sid)] and all(g in key_of for g in row["gana"]), ek
            ov["sutra_aliases"][sid] = row["gana"]
    for key, (sutra, parent, first, size, why) in SUB_GANAS.items():
        ov["sub_ganas"][key] = {"sutra": sutra, "of": parent, "from": first, "size": size, "evidence": why}
    report["ganapatha_overlay"] = {"akrti_flags": len(ov["akrti"]), "expansions": {k: {n: len(v) for n, v in d.items()} for k, d in ov["expansions"].items()},
                                   "gaNas_with_notes": len(ov["extra"]), "log": log}
    (IN / "ganapatha_overlay.json").write_text(json.dumps(ov, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return ov


def _first_member(text: str) -> str:
    """The member a Kāśikā sentence on a one-word gaṇasūtra names: 'svamityetacchabdarūpam' / 'antaramityetacchabdarūpam' → sva / antara."""
    m = re.search(r"([ऀ-ॿ]+)मित्येतच्छब्दरूपं", text)
    return m.group(1)


def samkhya(report: dict) -> None:
    """1.1.23: the sūtra names bahu, gaṇa, vatu, ḍati (Kāśikā's first sentence); the primitive numerals are 'laukika' and are not a pāṭha (Kāśikā 5.2.56)."""
    t = _kashika()[kkey("1.1.23")]
    named = _tokens(re.match(r"^(.*?) इत्येते", t).group(1))
    assert named == ["बहु", "गण", "वतु", "डति"], named
    out = {"_doc": "saṃkhyā words named by 1.1.23 (bahu-gaṇa-vatu-ḍati saṃkhyā). Generated by tools/intake_patha.py. -vatup and -ḍati words are tagged by their pratyaya at run time (5.2.39, 5.2.41); the primitive numeral stems (eka … sahasra …) are laukika and still need a source (Kāśikā 5.2.56 viṃśatyādayo laukikāḥ saṃkhyāśabdāḥ).",
           "source": "Kāśikā 1.1.23", "sutra_named": [{"dev": w, "slp1": sl(w)} for w in named], "laukika_numerals": {"status": "source-needed", "entries": []}}
    # The ṣaṭ-saṃjñaka numerals: the Kāśikā on 1.1.24 names them (षट्; पञ्च सप्त नव दश) and on 7.1.21 / 1.1.24 the aṣṭan (अष्टानाम्).
    # Only these six are entered; eka, dvi, tri, catur, viṃśati … stay source-needed.
    k24 = _kashika()[kkey("1.1.24")]
    for dev, stem_dev, evid in (("षट्", "षष्", "षट् तिष्ठन्ति"), ("पञ्च", "पञ्चन्", "नकारान्ता — पञ्च"), ("सप्त", "सप्तन्", "सप्त"), ("नव", "नवन्", "नव"),
                                ("दश", "दशन्", "दश"), ("अष्टानाम", "अष्टन्", "अष्टानामित्यत्र नुड्")):
        assert dev in k24, dev
        out["laukika_numerals"]["entries"].append({"dev": stem_dev, "slp1": sl(stem_dev), "evidence": f"Kāśikā 1.1.24: {evid}"})
    out["laukika_numerals"]["status"] = "kashika-1.1.24 (ṣaṭ-saṃjñaka only; the other numerals are source-needed)"
    (IN / "samkhya_patha.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    report["samkhya"] = {"sutra_named": [x["slp1"] for x in out["sutra_named"]], "laukika_numerals": out["laukika_numerals"]["status"]}


def main() -> int:
    report: dict = {}
    unadi(report)
    dhatu(report)
    gana_overlay(report)
    samkhya(report)
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
