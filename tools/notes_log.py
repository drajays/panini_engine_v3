"""python3 -m tools.notes_log — regenerate docs/NOTES_LOG.md from data/reviews/notes/*.json.
The log of every owner note, when it was written, when it was resolved, the verdict and the action. Read it BEFORE reviewing
notes: only status `open` rows need work; never re-judge a stamped note unless the owner reopens it."""
import glob, json, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = []
for f in glob.glob(str(ROOT / "data/reviews/notes/*.json")):
    d = json.load(open(f, encoding="utf-8"))
    for n in d["notes"]:
        rows.append((tuple(int(x) for x in d["sutra"].split(".")), d["sutra"], n))
rows.sort(key=lambda r: (r[0], r[2]["created"]))
cell = lambda s, k=160: " ".join(str(s or "").split())[:k].replace("|", "/")
out = ["# NOTES LOG (generated by `python3 -m tools.notes_log` — do not edit; the stamps live in data/reviews/notes/*.json)", "",
       f"Generated {time.strftime('%Y-%m-%d %H:%M')}. Rule: only `open` rows need work; a stamped note is not re-judged unless the owner reopens it. "
       "Statuses: confirmed (right, resolved or already true) · partly · refuted (engine correct) · ledgered (engine change tracked in docs/SHORTCUT_LEDGER.md).", "",
       "| sūtra | note | kind | written | status | stamped | note (start) | verdict (start) | evidence |", "|---|---|---|---|---|---|---|---|---|"]
for _, sid, n in rows:
    out.append(f"| {sid} | {n['id']} | {n.get('kind') or ''} | {n['created'][:16]} | {n['status']} | {(n.get('status_at') or (n['updated'] if n['status'] != 'open' else ''))[:16]} "
               f"| {cell(n['text'], 70)} | {cell(n.get('verdict'))} | {cell(n.get('evidence'), 70)} |")
out += ["", "## Actions taken from notes (manual, append-only)", "",
        "- 2026-11-15 · UI: repeated checked/blocked rows collapse to one clickable line; 🙈 hide per sūtra (kept in Copy to LLM) — prakriya.js (notes 1.2.45 d8b8c258f6, 4.1.2 571df57946).",
        "- 2026-11-15 · UI: 4.1.2 row shows the 7×3 sup table, chosen cell highlighted — prakriya.js supGridHtml (4.1.2 afeb5fc4e4).",
        "- 2026-11-15 · UI: ✎ on every step incl. Vidyut/corpus columns, the why-not box, and each Vidyut-only sūtra (8.4.68) — prakriya.js noteForm/wireOutNotes.",
        "- 2026-11-15 · Ledger: S181 (arthavattva Lexicon input), S182 (8.4.68 prayatna), S179 widened with 1.4.104.",
        "- 2026-11-15 · PENDING after the coverage run: 1.1.73 gloss says pada, Kāśikā says śabdarūpa (sutra_1_1_73.py:128); S179 (1.4.21/22/102–104 as rows).",
        "- 2026-11-15 · No change needed (engine correct): 2.1.1 and 1.2.46 not offered for rāma + au."]
(ROOT / "docs/NOTES_LOG.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(rows), "notes ->", "docs/NOTES_LOG.md")
