"""make status → docs/STATUS.md (generated; never hand-edit). Each line cites source + mtime."""
import json, time
from pathlib import Path
R = Path(__file__).resolve().parent.parent
def ts(p): return time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime(p.stat().st_mtime))
import sys; sys.path.insert(0, str(R))
import sutras  # noqa: F401
from engine import SUTRA_REGISTRY
from engine.coverage import honest_coverage
c, s = R/"sig/firing_coverage.json", R/"sig/sutra_class.json"       # Art. 16: the firing ledger, not the old sig/coverage.json
_h = honest_coverage(SUTRA_REGISTRY)
cov = {"implemented": _h["implemented"], "total": _h["registered"], "coverage_pct": _h["implemented_pct"]}
cls = json.loads(s.read_text())
conf = sum(r["status"].startswith("confident") for r in cls["rows"])
g = sorted((R/"bench/report").glob("2*.json"))
lk = sorted((R/"sig/lk_case_verdicts").glob("a*.json"), key=lambda p: p.stat().st_mtime)
stale = lk and lk[-1].stat().st_mtime > c.stat().st_mtime
out = ["# STATUS (generated by `make status`; do not edit)", "",
       f"- implemented {cov['implemented']}/{cov['total']} ({cov['coverage_pct']}%) — `sig/firing_coverage.json` @ {ts(c)}",
       f"- confident {conf} — `sig/sutra_class.json` @ {ts(s)}",
       f"- LK case verdicts — `sig/lk_case_verdicts/` @ {ts(lk[-1])}" if lk else "- no LK case verdicts",
       *(["- WARNING: the firing ledger is older than the LK verdicts — run `make coverage`, then `make confident`"] if stale else []),
       f"- latest bench file: `{g[-1].name}` @ {ts(g[-1])}" if g else "- no bench report"]
(R/"docs/STATUS.md").write_text("\n".join(out) + "\n"); print("\n".join(out))
